'use strict';
/**
 * HLS: synthetic segments + optional REAL local media.
 *
 * The reference backend has to serve *something* playable so the replica client
 * can be exercised end to end. It never proxies third-party streams (this
 * project refuses to do that — see docs/00-LEGAL-Y-ALCANCE.md §4.1). Two modes:
 *
 *  1. SYNTHETIC (default, streams 1001…) — null-packet MPEG-TS generated in
 *     memory. Structurally valid, but no decodable picture: it exercises the
 *     client's playlist/segment/buffering/error pipeline, nothing more.
 *
 *  2. REAL LOCAL MEDIA (streams with a manifest under backend/media/) — actual
 *     H.264/AAC segments generated by *this repo* (colour bars + tone via
 *     ffmpeg). Own content, no third party involved. This is what makes a
 *     channel genuinely play in a browser.
 *
 * A stream uses REAL media iff `backend/media/<id>.json` exists; its segments
 * live in `backend/media/segments/<id>-<n>.ts`. Everything else falls back to
 * synthetic, so the contract suite for 1001… is unaffected.
 */

const fs = require('fs');
const path = require('path');
const catalog = require('./catalog');

const SEG_SECONDS = 6;
const SEG_PER_PLAYLIST = 6;
const TS_PACKET = 188;
const TS_BYTES_PER_SEG = Math.round((SEG_SECONDS * 188 * 1024) / 8); // ~ rough, keeps it small

const MEDIA_DIR = path.join(__dirname, '..', '..', 'media');
const SEG_DIR = path.join(MEDIA_DIR, 'segments');

/* ------------------------------------------------------- real-media lookup */

const manifestCache = new Map();

/**
 * Read backend/media/<id>.json (cached). Returns null when the stream has no
 * real media, i.e. it should be served synthetically.
 */
function realManifest(streamId) {
  const id = String(streamId);
  if (manifestCache.has(id)) return manifestCache.get(id);
  let m = null;
  try {
    const file = path.join(MEDIA_DIR, `${id}.json`);
    m = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!Array.isArray(m.durations) || !m.durations.length) m = null;
  } catch (_) {
    m = null;
  }
  manifestCache.set(id, m);
  return m;
}

/** Absolute path of a real segment, or null if absent. Guards traversal. */
function realSegmentPath(streamId, index) {
  const name = `${streamId}-${index}.ts`;
  const p = path.join(SEG_DIR, name);
  if (!p.startsWith(SEG_DIR + path.sep)) return null; // paranoia: no traversal
  try {
    return fs.statSync(p).isFile() ? p : null;
  } catch (_) {
    return null;
  }
}

/* ---------------------------------------------------------------- playlist */

/**
 * Media playlist for a channel.
 *
 * Segment URIs are RELATIVE (`../../segments/<id>-<i>.ts`). Absolute URLs
 * derived from the Host header break whenever the backend sits behind a proxy
 * or a preview tunnel: the playlist would tell the player to fetch
 * `http://localhost:8080/...`, unreachable from the user's browser. Relative
 * URIs resolve against the playlist URL and work everywhere.
 *
 * Real-media streams emit their true per-segment durations and an
 * `#EXT-X-ENDLIST` (VOD); synthetic streams keep the fixed-duration EVENT shape.
 */
function mediaPlaylist(streamId, { vod = false } = {}) {
  const stream = catalog.findStream(streamId);
  const name = stream ? stream.name : `channel ${streamId}`;
  const man = realManifest(streamId);

  const isVod = vod || !!man; // real local clips are finite → VOD
  const targetDuration = man ? Math.ceil(Math.max(...man.durations)) : SEG_SECONDS;

  const lines = ['#EXTM3U', '#EXT-X-VERSION:3'];
  lines.push(`#EXT-X-TARGETDURATION:${targetDuration}`);
  lines.push('#EXT-X-MEDIA-SEQUENCE:0');
  lines.push(`#EXT-X-PLAYLIST-TYPE:${isVod ? 'VOD' : 'EVENT'}`);
  lines.push(`#EXT-X-SESSION-DATA:DATA-ID="com.dramalive-replica.title",VALUE="${escapeAttr(name)}"`);

  if (man) {
    man.durations.forEach((d, i) => {
      lines.push(`#EXTINF:${Number(d).toFixed(3)},`);
      lines.push(`../../segments/${streamId}-${i}.ts`);
    });
    lines.push('#EXT-X-ENDLIST');
  } else {
    for (let i = 0; i < SEG_PER_PLAYLIST; i++) {
      lines.push(`#EXTINF:${SEG_SECONDS}.000,`);
      // desde /hls/<id>/index.m3u8 → /segments/<id>-<i>.ts
      lines.push(`../../segments/${streamId}-${i}.ts`);
    }
    if (isVod) lines.push('#EXT-X-ENDLIST');
  }

  return lines.join('\n') + '\n';
}

/**
 * Master playlist with a single variant. Kept as a master (rather than serving
 * the media playlist directly) because that is what real panels do and clients
 * commonly branch on it. Real-media streams advertise their true
 * CODECS/RESOLUTION/BANDWIDTH so MSE picks the right demux path.
 */
function masterPlaylist(streamId, { relPrefix = '../' } = {}) {
  const stream = catalog.findStream(streamId);
  const man = realManifest(streamId);

  let codecs, bandwidth, resolution;
  if (man) {
    codecs = man.codecs || 'avc1.42001e,mp4a.40.2';
    bandwidth = man.bandwidth || 200000;
    resolution = man.resolution ? `RESOLUTION=${man.resolution},` : '';
  } else {
    const audioOnly = stream && /audio|tone|radio/i.test(stream.name || '');
    codecs = audioOnly ? 'mp4a.40.2' : 'avc1.4d401f,mp4a.40.2';
    bandwidth = audioOnly ? 128000 : 2000000;
    resolution = audioOnly ? '' : 'RESOLUTION=1280x720,';
  }

  return [
    '#EXTM3U',
    '#EXT-X-VERSION:3',
    `#EXT-X-STREAM-INF:BANDWIDTH=${bandwidth},${resolution}CODECS="${codecs}",NAME="referencia"`,
    // URI relativa a la playlist maestra. La profundidad DEPENDE de la ruta:
    //   /live/<user>/<pass>/<id>.m3u8   → 3 niveles  → ../../../hls/…
    //   /live/<id>.m3u8                 → 1 nivel    → ../hls/…
    // El caller calcula relPrefix; ver routes/hls.js.
    `${relPrefix}hls/${streamId}/index.m3u8`,
    '',
  ].join('\n');
}

/* ---------------------------------------------------------------- segments */

/**
 * Segment bytes for a stream.
 *
 * REAL media: read backend/media/segments/<id>-<idx>.ts (own generated
 * H.264/AAC). Falls back to a synthetic null-packet TS when the file is absent,
 * so a missing/partial clip degrades gracefully instead of 500-ing.
 *
 * SYNTHETIC: a minimal, structurally valid MPEG-TS segment of 188-byte null
 * packets (PID 0x1fff). Real decoders show black/silence or refuse it — fine,
 * because the goal there is to exercise the *client's* HLS pipeline (playlist
 * parsing, segment fetching, buffering, error handling), not to ship video.
 */
function segment(streamId, index) {
  const real = realSegmentPath(streamId, index);
  if (real) {
    try {
      return fs.readFileSync(real);
    } catch (_) {
      /* cae abajo al sintético */
    }
  }

  const packets = Math.max(8, Math.round(TS_BYTES_PER_SEG / TS_PACKET / 64));
  const buf = Buffer.alloc(packets * TS_PACKET, 0xff);
  for (let p = 0; p < packets; p++) {
    const off = p * TS_PACKET;
    buf[off] = 0x47; // sync byte
    buf[off + 1] = 0x1f; // PID 0x1fff = null packet
    buf[off + 2] = 0xff;
    buf[off + 3] = 0x10; // adaptation: payload only, continuity counter 0
    // stamp stream/segment so a hexdump is self-describing during debugging
    const tag = Buffer.from(`dl:${streamId}:${index}`, 'ascii');
    tag.copy(buf, off + 4, 0, Math.min(tag.length, TS_PACKET - 8));
  }
  return buf;
}

function escapeAttr(s) {
  return String(s).replace(/"/g, '\\"');
}

module.exports = {
  mediaPlaylist,
  masterPlaylist,
  segment,
  realManifest,
  SEG_SECONDS,
};
